// Writes src/styles/theme.tokens.scss (CSS custom properties) from site.config.json.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';

const cfg = JSON.parse(readFileSync('site.config.json', 'utf8'));
const t = cfg.theme;
const kebab = (s) => s.replace(/[A-Z]/g, (m) => '-' + m.toLowerCase());
const colorVars = (colors, indent) =>
  Object.entries(colors)
    .map(([k, v]) => `${indent}--color-${kebab(k)}: ${v};`)
    .join('\n');

const density = { compact: 0.8, comfortable: 1, spacious: 1.2 }[t.density] ?? 1;
const stack = (f) => `'${f}', system-ui, -apple-system, 'Segoe UI', sans-serif`;

let css = `/* GENERATED by tools/gen-theme.mjs from site.config.json — do not edit. */
:root {
${colorVars(t.colors, '  ')}
  --font-heading: ${stack(t.fonts.heading)};
  --font-body: ${stack(t.fonts.body)};
  --font-indic: '${t.fonts.indic}', ${stack(t.fonts.body)};
  --radius: ${t.radius};
  --density: ${density};
}
`;

if (t.colorsDark) {
  if (t.darkMode === 'dark') {
    css += `:root {\n${colorVars(t.colorsDark, '  ')}\n}\n`;
  } else if (t.darkMode === 'auto') {
    css += `@media (prefers-color-scheme: dark) {\n  :root {\n${colorVars(t.colorsDark, '    ')}\n  }\n}\n`;
  }
}

mkdirSync('src/styles', { recursive: true });
writeFileSync('src/styles/theme.tokens.scss', css);
console.log('theme tokens written');
