// Scans content/<locale>/ and writes src/generated/content-index.ts.
// Fails the build on malformed content, so mistakes never reach production.
import { readFileSync, writeFileSync, readdirSync, existsSync, mkdirSync } from 'node:fs';
import { join, basename } from 'node:path';

const cfg = JSON.parse(readFileSync('site.config.json', 'utf8'));
const { locales, defaultLocale } = cfg.i18n;

const imports = [];
const pages = [];
const news = [];
const announcements = {};
let n = 0;
const errors = [];

function load(file, locale, kind) {
  const data = JSON.parse(readFileSync(file, 'utf8'));
  const slug = data.slug || basename(file, '.json');
  const id = `c${n++}`;
  imports.push(`import ${id} from '../../${file.replaceAll('\\', '/')}';`);
  return { id, slug, data };
}

const jsonFiles = (dir) =>
  existsSync(dir) ? readdirSync(dir).filter((f) => f.endsWith('.json')).map((f) => join(dir, f)) : [];

const keysByLocale = {};
for (const locale of locales) {
  keysByLocale[locale] = new Set();
  const seen = new Set();
  for (const file of jsonFiles(join('content', locale, 'pages'))) {
    const { id, slug, data } = load(file, locale, 'page');
    if (!data.title) errors.push(`${file}: missing "title"`);
    if (!data.translationKey) errors.push(`${file}: missing "translationKey"`);
    if (!Array.isArray(data.blocks)) errors.push(`${file}: "blocks" must be an array`);
    if (seen.has(slug)) errors.push(`${file}: duplicate slug "${slug}" in ${locale}`);
    seen.add(slug);
    keysByLocale[locale].add(data.translationKey);
    pages.push(`  { ...(${id} as object), locale: '${locale}', slug: ${JSON.stringify(slug)} }`);
  }
  for (const file of jsonFiles(join('content', locale, 'news'))) {
    const { id, slug, data } = load(file, locale, 'news');
    if (!data.title || !data.date) errors.push(`${file}: news needs "title" and "date"`);
    news.push(`  { ...(${id} as object), locale: '${locale}', slug: ${JSON.stringify(slug)} }`);
  }
  const ann = join('content', locale, 'settings', 'announcement.json');
  if (existsSync(ann)) {
    const { id } = load(ann, locale, 'settings');
    announcements[locale] = id;
  }
}

for (const locale of locales) {
  if (locale === defaultLocale) continue;
  for (const key of keysByLocale[defaultLocale]) {
    if (!keysByLocale[locale].has(key)) {
      console.warn(`warn: page "${key}" has no ${locale} translation (falls back to ${defaultLocale}, noindex)`);
    }
  }
}

if (errors.length) {
  console.error('Content errors:\n  ' + errors.join('\n  '));
  process.exit(1);
}

const annEntries = Object.entries(announcements)
  .map(([l, id]) => `  ${l}: ${id} as Announcement`)
  .join(',\n');

const out = `// GENERATED by tools/gen-content-index.mjs — do not edit.
import type { Announcement, NewsItem, Page } from '../app/core/content/content.types';
import type { Locale } from '../app/core/config/site-config';
${imports.join('\n')}

export const PAGES = [
${pages.join(',\n')}
] as unknown as Page[];

export const NEWS = [
${news.join(',\n')}
] as unknown as NewsItem[];

export const ANNOUNCEMENTS: Partial<Record<Locale, Announcement>> = {
${annEntries}
};
`;

mkdirSync('src/generated', { recursive: true });
writeFileSync('src/generated/content-index.ts', out);
console.log(`content index: ${pages.length} pages, ${news.length} news items`);
